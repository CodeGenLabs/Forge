"""Four repairs the first real change through the lifecycle made necessary.

Each is here because it cost real time, not because it looked wrong on a
reading: a wrapped task silently losing its requirement id, an artifact with a
declared template and no template, a verification reporting `fail` because a
command was not on PATH, and an open change reporting its own requirements as
dangling for as long as anybody was working on it.
"""

from __future__ import annotations

from datetime import date

import pytest

from forge import change, scaffold, trace, verify
from forge.cli import main

TODAY = date(2026, 9, 11)


@pytest.fixture
def opened(repo):
    repo.write("src/app.py", "def go():\n    return 1\n")
    main(["init", "--repo", str(repo.root)])
    repo.commit("a scaffolded project")
    change.new_change(repo.root, "add a thing", today=TODAY)
    repo.commit("open a change")
    return repo


def item(repo):
    return change.find_change(repo.root, "1")


# ---------------------------------------------------------------------------
# A task is a bullet, not a line (PIT-bullet-continuation-lines)
# ---------------------------------------------------------------------------

def test_a_wrapped_task_keeps_its_continuation(opened):
    """The incident: a `REQ-` id on the second physical line was invisible, so
    `trace.requirement_task_coverage` blocked with a page of errors that were
    all wrong."""
    opened.write("changes/0001-add-a-thing/tasks.md",
                 "# Tasks\n\n"
                 "- [ ] Add the thing to the module, then wire it up so that\n"
                 "      it discharges REQ-thing-1 end to end.\n")
    tasks = item(opened).tasks()
    assert len(tasks) == 1
    done, text = tasks[0]
    assert done is False
    assert "REQ-thing-1" in text


def test_an_unindented_paragraph_is_not_swallowed_into_the_last_task(opened):
    """The indent requirement is the whole guard: without it, prose after the
    list joins the final task and every task list grows a tail."""
    opened.write("changes/0001-add-a-thing/tasks.md",
                 "# Tasks\n\n"
                 "- [x] REQ-thing-1: do the thing.\n"
                 "\n"
                 "A closing paragraph that is not a task.\n")
    tasks = item(opened).tasks()
    assert len(tasks) == 1
    assert tasks[0] == (True, "REQ-thing-1: do the thing.")


def test_several_wrapped_tasks_stay_separate(opened):
    opened.write("changes/0001-add-a-thing/tasks.md",
                 "# Tasks\n\n"
                 "- [x] REQ-a: the first task, which is long enough\n"
                 "      to wrap onto a second line.\n"
                 "- [ ] REQ-b: the second task, also long enough\n"
                 "      to wrap.\n")
    tasks = item(opened).tasks()
    assert [d for d, _ in tasks] == [True, False]
    assert "REQ-a" in tasks[0][1] and "second line" in tasks[0][1]
    assert "REQ-b" in tasks[1][1] and "to wrap" in tasks[1][1]


