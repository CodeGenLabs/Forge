def test_every_templated_artifact_has_a_template():
    """The schema declared `template:` for five artifacts and nothing read it."""
    from forge import schema as schema_mod

    loaded = schema_mod.parse_schema(schema_mod.builtin_schema_text("feature"),
                                     source="feature.yaml")
    declared = {a.id for a in loaded.artifacts if a.template}
    assert declared == set(scaffold.CHANGE_TEMPLATES)


def test_verification_has_no_template():
    """It is generated by `forge verify`. A template for it would be a place to
    write a result by hand, which is what this file exists to prevent."""
    assert scaffold.change_template("verification", "x") is None


def test_a_scaffolded_artifact_does_not_count_as_complete(opened):
    code = main(["instructions", "proposal", "--change", "1", "--write",
                 "--repo", str(opened.root)])
    assert code == 0

    states = {s.id: s for s in item(opened).state(
        __import__("forge.schema", fromlist=["x"]).load_schema(opened.root, "feature"))}
    assert states["proposal"].state == change.MISSING
    assert states["proposal"].reason
    assert states["proposal"].files == ["changes/0001-add-a-thing/proposal.md"]


def test_deleting_the_marker_completes_the_artifact(opened):
    from forge import schema as schema_mod

    main(["instructions", "proposal", "--change", "1", "--write",
          "--repo", str(opened.root)])
    target = opened.root / "changes/0001-add-a-thing/proposal.md"
    text = target.read_text(encoding="utf-8")
    target.write_text(text.replace(change.TEMPLATE_MARKER + "\n", ""),
                      encoding="utf-8", newline="\n")

    loaded = schema_mod.load_schema(opened.root, "feature")
    states = {s.id: s for s in item(opened).state(loaded)}
    assert states["proposal"].state == change.COMPLETE


def test_a_glob_artifact_needs_a_name(opened):
    """`spec/**/*.md` names a shape. Guessing the capability would produce
    `spec/spec.md` on every change - a name that tells a later reader nothing."""
    assert main(["instructions", "spec", "--change", "1", "--write",
                 "--repo", str(opened.root)]) == 2
    assert main(["instructions", "spec", "--change", "1", "--write", "payments",
                 "--repo", str(opened.root)]) == 0
    assert (opened.root / "changes/0001-add-a-thing/spec/payments/spec.md").is_file()


def test_scaffolding_never_overwrites(opened):
    main(["instructions", "proposal", "--change", "1", "--write",
          "--repo", str(opened.root)])
    target = opened.root / "changes/0001-add-a-thing/proposal.md"
    target.write_text("written by a human\n", encoding="utf-8", newline="\n")
    main(["instructions", "proposal", "--change", "1", "--write",
          "--repo", str(opened.root)])
    assert target.read_text(encoding="utf-8") == "written by a human\n"


# ---------------------------------------------------------------------------
# "We cannot run it" is not "it failed"
# ---------------------------------------------------------------------------

def test_a_command_not_on_path_is_reported(tmp_path):
    assert verify.resolve_command(tmp_path, "definitely-not-a-real-binary --x")
    assert verify.resolve_command(tmp_path, "") == "the command is empty"


def test_a_resolvable_command_reports_nothing(tmp_path):
    assert verify.resolve_command(tmp_path, "git status") is None


def test_a_path_or_shell_construct_is_left_to_the_shell(tmp_path):
    """The shell is better at shell than this function is."""
    assert verify.resolve_command(tmp_path, ".venv/bin/pytest -q") is None
    assert verify.resolve_command(tmp_path, "FOO=1 x && y") is None


def test_a_project_virtualenv_is_named_in_the_message(tmp_path):
    (tmp_path / ".venv/bin").mkdir(parents=True)
    (tmp_path / ".venv/bin/pytest").write_text("#!/bin/sh\n", encoding="utf-8")
    message = verify.resolve_command(tmp_path, "pytest -q")
    assert message and ".venv/bin/pytest" in message


def test_an_unrunnable_command_is_unavailable_not_failed(opened):
    """`fail` says the suite ran and did not pass. Saying that when the suite
    was never started is the one thing a verification report must never do."""
    (opened.root / ".forge/config.yaml").write_text(
        "commands:\n  test: definitely-not-a-real-binary\n",
        encoding="utf-8", newline="\n")
    report = verify.verify(opened.root, item(opened))
    assert report["gates"]["tests"]["status"] == "unavailable"
    # Other conditions may legitimately fail in this fixture; what matters is
    # that `tests` is not one of them.
    assert "tests" not in report["failing"]
    assert "tests" in report["unproven"]


def test_the_timeout_comes_from_config(opened):
    (opened.root / ".forge/config.yaml").write_text(
        "commands:\n  timeout: 7\n  test: git status\n",
        encoding="utf-8", newline="\n")
    report = verify.verify(opened.root, item(opened))
    # `timeout` is a bound, never a command: it must not be run as one.
    assert report["gates"]["tests"]["cmd"] == "git status"


# ---------------------------------------------------------------------------
# An open change defines its own requirements
# ---------------------------------------------------------------------------

DELTA = """\
# Payments

## Purpose

What this capability is for, stated in a sentence long enough to be a purpose.

## ADDED Requirements

### Requirement: REQ-pay-1 - money never moves twice

The system SHALL reject a duplicate capture.

#### Scenario: a repeated capture

- Given a capture that already settled
- When the same capture arrives again
- Then it is rejected
"""


def test_an_open_delta_defines_its_requirements(opened):
    """Otherwise a change reports dangling references from the moment it writes
    its spec until the moment it is archived - which is the whole time anybody
    is working on it."""
    opened.write("changes/0001-add-a-thing/spec/payments.md", DELTA)
    opened.commit("a spec delta")

    index = trace.build_trace(opened.root)
    entry = index["ids"]["REQ-pay-1"]
    assert entry["defined_in"].endswith("spec/payments.md:9")
    assert entry["provisional"] is True
    assert "REQ-pay-1" not in index["summary"]["dangling_references"]


def test_an_archived_delta_does_not_define_anything(opened):
    """The archive is never an input to any phase, so it is not a definition."""
    opened.write("changes/archive/0001-add-a-thing/spec/payments.md", DELTA)
    opened.commit("an archived delta")

    index = trace.build_trace(opened.root)
    assert "REQ-pay-1" not in index["ids"]


# ---------------------------------------------------------------------------
# `forge doctor` meets the unresolvable command, not `forge verify`
# ---------------------------------------------------------------------------

def test_doctor_reports_an_unresolvable_command(opened, capsys):
    (opened.root / ".forge/config.yaml").write_text(
        "commands:\n  test: definitely-not-a-real-binary -q\n",
        encoding="utf-8", newline="\n")
    code = main(["doctor", "--repo", str(opened.root)])
    out = capsys.readouterr().out
    assert code == 1
    assert "definitely-not-a-real-binary" in out
    assert "not on PATH" in out


def test_doctor_is_clean_when_every_command_resolves(opened, capsys):
    (opened.root / ".forge/config.yaml").write_text(
        "commands:\n  test: git status\n", encoding="utf-8", newline="\n")
    assert main(["doctor", "--repo", str(opened.root)]) == 0


def test_doctor_does_not_try_to_run_the_timeout(opened, capsys):
    """`timeout` lives under `commands:` and configures the runner. Resolving
    it would report `1800` as a missing program."""
    (opened.root / ".forge/config.yaml").write_text(
        "commands:\n  timeout: 1800\n  test: git status\n",
        encoding="utf-8", newline="\n")
    assert main(["doctor", "--repo", str(opened.root)]) == 0
    assert "1800" not in capsys.readouterr().out


def test_doctor_says_so_when_nothing_is_declared(opened, capsys):
    (opened.root / ".forge/config.yaml").write_text("version: 1\n",
                                                    encoding="utf-8", newline="\n")
    assert main(["doctor", "--repo", str(opened.root)]) == 0
    assert "none declared" in capsys.readouterr().out


